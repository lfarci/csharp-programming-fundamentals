    // L11 · Count from a to b
    // Exercise page: exercises/L11-count-from-a-to-b.md
    public static class L11_CountFromAToB
    {
        public static void PrintFromTo(int a, int b)
        {
            for (int i = a; i <= b; i++)
            {
                Console.WriteLine(i);
            }
        }
    }
}
